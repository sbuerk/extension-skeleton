#!/usr/bin/env bash

#
# initializeRepository.sh — turn this template repository into a concrete TYPO3
# extension repository.
#
# Given the GitHub repository reference of the new repository, every identifier
# derived from the template is rewritten throughout the working tree:
#
#   <owner>/<repository>  ->  composer package name (composer.json)
#   <repository>          ->  TYPO3 extension key (ext_emconf.php), normalized
#                             to lowercase with "-", "." and " " turned into "_"
#   <OWNER>\<Repository>  ->  PHP root namespace in every PHP file, with the
#                             owner in capital letters and the repository name
#                             camel cased, including the core version aware
#                             sub-namespaces Core13\ and Core14\, the test
#                             namespace and the dependency injection wiring in
#                             Configuration/Services.php
#   "Owner Repository"    ->  human readable extension title
#
# The repository URLs in composer.json (homepage, support.issues,
# support.source) are additionally set explicitly, so they point at the new
# repository even when they did not contain the old package name.
#
# The bare owner and the bare vendor namespace are rewritten as well, so the
# template author does not stay behind. Dependency package names are excluded
# from that: a dependency published by the same owner keeps its name, and so
# does the class generated by the "sbuerk/fixture-packages" composer plugin.
#
# Renaming the PHP namespace can change the alphabetical order of the "use"
# statements, so the coding guidelines are applied to the result afterwards
# (see --skip-cgl).
#
# Example:
#   Build/Scripts/initializeRepository.sh vendor/some-repository-name
#
#     composer package : vendor/some-repository-name
#     extension key    : some_repository_name
#     PHP namespaces   : VENDOR\SomeRepositoryName\
#                        VENDOR\SomeRepositoryName\Core13\
#                        VENDOR\SomeRepositoryName\Core14\
#                        VENDOR\SomeRepositoryName\Tests\
#
# The values to replace are read from composer.json instead of being hardcoded,
# which makes the script idempotent: it can be run again later to rename an
# already initialized repository.
#
# Usage:
#   Build/Scripts/initializeRepository.sh <owner>/<repository> [options]
#
# Options:
#   --dry-run              print every replacement without touching a file
#   --skip-cgl             do not apply the coding guidelines afterwards
#   --container-bin=<bin>  container runtime for the coding guidelines step,
#                          "docker" or "podman", passed on to runTests.sh as
#                          "-b". Defaults to whatever that script picks.
#   -h, --help             show this help
#
# GitHub Actions workflow files are never rewritten: the GITHUB_TOKEN of an
# Actions run may not update files below .github/workflows/, so the initialize
# workflow could not push the result. Workflow files must therefore not contain
# any of the identifiers above — derive them at runtime from composer.json
# instead, as .github/workflows/publish.yml does.
#
# This script only edits working-tree files. It performs no git or network
# operations — committing the result is left to the caller, see the "Repository
# initialization" section of README.md.
#

set -euo pipefail

# ---------------------------------------------------------------------------
# Always operate from the repository root. This script lives in
# <root>/Build/Scripts, so the repository root is two directories up.
# ---------------------------------------------------------------------------
THIS_SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null && pwd)"
ROOT_DIR="$(cd -- "${THIS_SCRIPT_DIR}/../.." >/dev/null && pwd)"
cd "${ROOT_DIR}"

# Path of this script relative to the repository root. It is excluded from the
# replacements so that the usage examples above keep their generic wording.
THIS_SCRIPT_RELATIVE="Build/Scripts/$(basename -- "${BASH_SOURCE[0]}")"

DRY_RUN=0
SKIP_CGL=0
CONTAINER_BIN=""

info() { printf '>> %s\n' "$*"; }
step() { printf '   [%s] %s\n' "$1" "$2"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

usage() {
    sed -n '3,62p' "${BASH_SOURCE[0]}" | sed 's/^#\{0,1\} \{0,1\}//'
}

# ---------------------------------------------------------------------------
# Argument parsing
# ---------------------------------------------------------------------------
REPOSITORY_REFERENCE=""

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run)  DRY_RUN=1 ;;
        --skip-cgl) SKIP_CGL=1 ;;
        --container-bin=*)
            CONTAINER_BIN="${1#*=}"
            if ! [[ "${CONTAINER_BIN}" =~ ^(docker|podman)$ ]]; then
                die "Invalid --container-bin '${CONTAINER_BIN}': expected docker or podman"
            fi
            ;;
        -h|--help)  usage; exit 0 ;;
        -*)         die "Unknown option: $1 (see --help)" ;;
        *)
            if [ -n "${REPOSITORY_REFERENCE}" ]; then
                die "Unexpected extra argument: $1 (see --help)"
            fi
            REPOSITORY_REFERENCE="$1"
            ;;
    esac
    shift
done

if [ -z "${REPOSITORY_REFERENCE}" ]; then
    die "Missing <owner>/<repository> argument (see --help)"
fi

if ! [[ "${REPOSITORY_REFERENCE}" =~ ^([A-Za-z0-9][A-Za-z0-9._-]*)/([A-Za-z0-9][A-Za-z0-9._-]*)$ ]]; then
    die "Invalid repository reference '${REPOSITORY_REFERENCE}': expected <owner>/<repository>, for example vendor/some-repository-name"
fi
NEW_OWNER="${BASH_REMATCH[1]}"
NEW_REPOSITORY="${BASH_REMATCH[2]}"

# ---------------------------------------------------------------------------
# Resolve + verify tooling.
# ---------------------------------------------------------------------------
resolve_bin() {
    local var="$1" name="$2" path
    path="$(command -v "${name}" 2>/dev/null || true)"
    if [ -z "${path}" ]; then
        die "Required tool '${name}' not found on PATH."
    fi
    printf -v "${var}" '%s' "${path}"
}
resolve_bin PHP php
resolve_bin AWK awk

if [ ! -f composer.json ]; then
    die "No composer.json found in ${ROOT_DIR}."
fi

# Used to reformat the markdown tables at the end. Verified here rather than
# there, because a missing file would only make that step quietly do nothing.
MARKDOWN_TABLE_FORMATTER="${THIS_SCRIPT_DIR}/MarkdownTableFormatter.php"
if [ ! -f "${MARKDOWN_TABLE_FORMATTER}" ]; then
    die "Required file '${MARKDOWN_TABLE_FORMATTER}' not found."
fi

# ---------------------------------------------------------------------------
# composer.json access.
#
# php rather than jq: php is available wherever this repository is worked on,
# and the container images of Build/Scripts/runTests.sh do not ship jq — which
# is what lets the "checkRepositoryInitialization" gate run this script.
#
# Values are decoded into objects, not associative arrays, so an empty JSON
# object survives the round trip as "{}" instead of turning into "[]".
# ---------------------------------------------------------------------------
composer_json_read() {
    "${PHP}" -r '
        $data = json_decode((string)file_get_contents("composer.json"));
        if (!$data instanceof stdClass) {
            fwrite(STDERR, "composer.json does not contain a JSON object." . PHP_EOL);
            exit(1);
        }
        switch ($argv[1]) {
            case "name":
                echo $data->name ?? "", PHP_EOL;
                break;
            case "extension-key":
                echo $data->extra->{"typo3/cms"}->{"extension-key"} ?? "", PHP_EOL;
                break;
            case "dependencies":
                foreach ([$data->require ?? null, $data->{"require-dev"} ?? null] as $section) {
                    if (!$section instanceof stdClass) {
                        continue;
                    }
                    foreach (array_keys(get_object_vars($section)) as $package) {
                        if (str_contains($package, "/")) {
                            echo $package, PHP_EOL;
                        }
                    }
                }
                break;
            case "namespace":
            case "namespace-dev":
                $section = $argv[1] === "namespace" ? ($data->autoload ?? null) : ($data->{"autoload-dev"} ?? null);
                $map = $section->{"psr-4"} ?? null;
                $keys = $map instanceof stdClass ? array_keys(get_object_vars($map)) : [];
                usort($keys, static fn(string $a, string $b): int => strlen($a) <=> strlen($b));
                echo $keys[0] ?? "", PHP_EOL;
                break;
            default:
                fwrite(STDERR, "Unknown composer.json query: " . $argv[1] . PHP_EOL);
                exit(1);
        }
    ' -- "$1"
}

# Point the repository URLs at the new repository. Only keys that already exist
# are touched.
composer_json_write_urls() {
    "${PHP}" -r '
        $data = json_decode((string)file_get_contents("composer.json"));
        $url = $argv[1];
        if (property_exists($data, "homepage")) {
            $data->homepage = $url;
        }
        if (($data->support ?? null) instanceof stdClass) {
            if (property_exists($data->support, "issues")) {
                $data->support->issues = $url . "/issues";
            }
            if (property_exists($data->support, "source")) {
                $data->support->source = $url;
            }
        }
        $encoded = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        file_put_contents("composer.json", $encoded . PHP_EOL);
    ' -- "$1"
}

# ---------------------------------------------------------------------------
# Derivation helpers
# ---------------------------------------------------------------------------

# Lowercase a string.
to_lower() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]'; }

# TYPO3 extension key: lowercase, separators become underscores, remaining
# invalid characters are dropped, underscores collapsed and trimmed.
to_extension_key() {
    local value
    value="$(to_lower "$1")"
    value="${value//[-. ]/_}"
    value="$(printf '%s' "${value}" | tr -cd 'a-z0-9_')"
    while [[ "${value}" == *__* ]]; do value="${value//__/_}"; done
    value="${value#_}"
    value="${value%_}"
    printf '%s' "${value}"
}

# PHP vendor namespace part: the owner in capital letters, separators dropped.
to_vendor_namespace() {
    printf '%s' "$1" | tr -d '[:space:]._-' | tr '[:lower:]' '[:upper:]'
}

# PHP package namespace part: camel cased repository name, for example
# "some-repository-name" becomes "SomeRepositoryName".
to_camel_case() {
    printf '%s' "$1" | "${AWK}" '{
        parts = split($0, part, /[-._ ]+/)
        out = ""
        for (i = 1; i <= parts; i++) {
            if (part[i] == "") { continue }
            out = out toupper(substr(part[i], 1, 1)) substr(part[i], 2)
        }
        print out
    }'
}

# Human readable title, for example "some-repository-name" becomes
# "Some Repository Name".
to_title() {
    printf '%s' "$1" | "${AWK}" '{
        parts = split($0, part, /[-._ ]+/)
        out = ""
        for (i = 1; i <= parts; i++) {
            if (part[i] == "") { continue }
            if (out != "") { out = out " " }
            out = out toupper(substr(part[i], 1, 1)) substr(part[i], 2)
        }
        print out
    }'
}

# ---------------------------------------------------------------------------
# Read the current values from composer.json.
# ---------------------------------------------------------------------------
CURRENT_PACKAGE="$(composer_json_read name)"
CURRENT_EXTENSION_KEY="$(composer_json_read extension-key)"

if [ -z "${CURRENT_PACKAGE}" ]; then
    die "No 'name' found in composer.json."
fi
if [ -z "${CURRENT_EXTENSION_KEY}" ]; then
    die "No 'extra.typo3/cms.extension-key' found in composer.json."
fi

CURRENT_OWNER="${CURRENT_PACKAGE%%/*}"
CURRENT_REPOSITORY="${CURRENT_PACKAGE#*/}"
CURRENT_VENDOR_NAMESPACE="$(to_vendor_namespace "${CURRENT_OWNER}")"
CURRENT_PACKAGE_NAMESPACE="$(to_camel_case "${CURRENT_REPOSITORY}")"
CURRENT_TITLE="$(to_title "${CURRENT_REPOSITORY}")"

# ---------------------------------------------------------------------------
# Derive the new values.
# ---------------------------------------------------------------------------
NEW_OWNER_LOWER="$(to_lower "${NEW_OWNER}")"
NEW_REPOSITORY_LOWER="$(to_lower "${NEW_REPOSITORY}")"
NEW_PACKAGE="${NEW_OWNER_LOWER}/${NEW_REPOSITORY_LOWER}"
NEW_EXTENSION_KEY="$(to_extension_key "${NEW_REPOSITORY}")"
NEW_VENDOR_NAMESPACE="$(to_vendor_namespace "${NEW_OWNER}")"
NEW_PACKAGE_NAMESPACE="$(to_camel_case "${NEW_REPOSITORY}")"
NEW_TITLE="$(to_title "${NEW_REPOSITORY}")"

if ! [[ "${NEW_EXTENSION_KEY}" =~ ^[a-z][a-z0-9_]*$ ]]; then
    die "Repository '${NEW_REPOSITORY}' does not yield a valid TYPO3 extension key (got '${NEW_EXTENSION_KEY}')."
fi
if ! [[ "${NEW_VENDOR_NAMESPACE}" =~ ^[A-Z][A-Z0-9]*$ ]]; then
    die "Owner '${NEW_OWNER}' does not yield a valid PHP namespace part (got '${NEW_VENDOR_NAMESPACE}')."
fi
if ! [[ "${NEW_PACKAGE_NAMESPACE}" =~ ^[A-Za-z][A-Za-z0-9]*$ ]]; then
    die "Repository '${NEW_REPOSITORY}' does not yield a valid PHP namespace part (got '${NEW_PACKAGE_NAMESPACE}')."
fi

info "initializeRepository ${NEW_PACKAGE}$([ "${DRY_RUN}" -eq 1 ] && echo '  [DRY-RUN]')"
step "info" "composer package : ${CURRENT_PACKAGE} -> ${NEW_PACKAGE}"
step "info" "extension key    : ${CURRENT_EXTENSION_KEY} -> ${NEW_EXTENSION_KEY}"
step "info" "PHP namespace    : ${CURRENT_VENDOR_NAMESPACE}\\${CURRENT_PACKAGE_NAMESPACE}\\ -> ${NEW_VENDOR_NAMESPACE}\\${NEW_PACKAGE_NAMESPACE}\\"
step "info" "extension title  : ${CURRENT_TITLE} -> ${NEW_TITLE}"

if [ "${CURRENT_PACKAGE}" = "${NEW_PACKAGE}" ]; then
    info "Repository is already initialized as '${NEW_PACKAGE}' — nothing to do."
    exit 0
fi

# ---------------------------------------------------------------------------
# Build the ordered replacement list. Order matters: the most specific pattern
# has to be replaced first, otherwise a shorter pattern consumes part of a
# longer one.
#
# The escaped namespace variant ("VENDOR\\Package") covers the JSON encoded
# occurrences in composer.json and the string literals in
# Configuration/Services.php.
#
# The list is applied in one pass, see the placeholder round trip further down:
# a new name may contain the old one, and no replacement may be applied to what
# an earlier one just wrote.
# ---------------------------------------------------------------------------
declare -a REPLACEMENT_SEARCH=()
declare -a REPLACEMENT_REPLACE=()

add_replacement() {
    if [ "$1" = "$2" ]; then
        return 0
    fi
    REPLACEMENT_SEARCH+=("$1")
    REPLACEMENT_REPLACE+=("$2")
}

add_replacement "${CURRENT_VENDOR_NAMESPACE}\\\\${CURRENT_PACKAGE_NAMESPACE}" "${NEW_VENDOR_NAMESPACE}\\\\${NEW_PACKAGE_NAMESPACE}"
add_replacement "${CURRENT_VENDOR_NAMESPACE}\\${CURRENT_PACKAGE_NAMESPACE}"   "${NEW_VENDOR_NAMESPACE}\\${NEW_PACKAGE_NAMESPACE}"
add_replacement "${CURRENT_PACKAGE}"                                          "${NEW_PACKAGE}"
add_replacement "${CURRENT_EXTENSION_KEY}"                                    "${NEW_EXTENSION_KEY}"
add_replacement "${CURRENT_REPOSITORY}"                                       "${NEW_REPOSITORY_LOWER}"
add_replacement "${CURRENT_TITLE}"                                            "${NEW_TITLE}"
add_replacement "${CURRENT_PACKAGE_NAMESPACE}"                                "${NEW_PACKAGE_NAMESPACE}"
add_replacement "${CURRENT_VENDOR_NAMESPACE}"                                 "${NEW_VENDOR_NAMESPACE}"
add_replacement "${CURRENT_OWNER}"                                            "${NEW_OWNER_LOWER}"

# ---------------------------------------------------------------------------
# Build the list of tokens which must survive the rewrite.
#
# The last two replacements above match the bare owner and the bare vendor
# namespace, so that the template author does not stay behind in prose, author
# fields and namespaces. Those matches are literal, and they therefore also hit
# things which are not identifiers of this repository at all — a dependency
# published by the same owner, and its PHP namespace. Rewriting either of them
# produces a repository that no longer resolves its own dependencies.
#
# Two sources, both derived rather than hardcoded, so dependencies added later
# are covered without touching this script:
#
#   1. Every dependency package name in composer.json. A dependency name is
#      never an identifier of this repository.
#   2. Every "<VendorNamespace>\<Segment>" found in the working tree whose
#      segment is not this repository's own package namespace. That covers the
#      namespaces of dependencies published by the same owner, for example
#      "SBUERK\TYPO3" of "sbuerk/typo3-site-based-test-trait" and
#      "SBUERK\AvailableFixturePackages" generated by "sbuerk/fixture-packages".
#      Both the plain and the JSON escaped spelling are collected.
#
# They are masked with a placeholder before the replacements are applied and
# restored afterwards.
# ---------------------------------------------------------------------------
declare -a PROTECTED_TOKENS=()
while IFS= read -r token; do
    [ -n "${token}" ] && PROTECTED_TOKENS+=("${token}")
done < <(composer_json_read dependencies)

# ---------------------------------------------------------------------------
# Collect the files to process: every tracked text file, without this script,
# the license, the GitHub Actions workflows and everything git-ignored or
# binary.
# ---------------------------------------------------------------------------
declare -a FILES=()
SKIPPED_WORKFLOW_FILES=0
while IFS= read -r file; do
    if [ "${file}" = "${THIS_SCRIPT_RELATIVE}" ] || [ "${file}" = "LICENSE" ]; then
        continue
    fi
    # Workflow files are left alone, see the note in the header above.
    if [[ "${file}" == .github/workflows/* ]]; then
        SKIPPED_WORKFLOW_FILES=$((SKIPPED_WORKFLOW_FILES + 1))
        continue
    fi
    # Symlinks — the agent instruction files, for example — point at a file
    # which is processed on its own. Following one would rewrite the target a
    # second time and report the change under the name of the link.
    if [ -L "${file}" ]; then
        continue
    fi
    if [ ! -f "${file}" ]; then
        continue
    fi
    # Skip binary and empty files.
    if ! grep -Iq . "${file}" 2>/dev/null; then
        continue
    fi
    FILES+=("${file}")
done < <(
    if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        git ls-files
    else
        find . -type f \
            -not -path './.git/*' \
            -not -path './.Build/*' \
            -not -path './Documentation-GENERATED-temp/*' \
            -printf '%P\n'
    fi
)

if [ "${#FILES[@]}" -eq 0 ]; then
    die "No files found to process in ${ROOT_DIR}."
fi

# Second source of protected tokens, see above: namespaces starting with the
# current vendor namespace but continuing with something other than this
# repository's package namespace. Needs the file list, hence its place here.
while IFS= read -r token; do
    [ -n "${token}" ] && PROTECTED_TOKENS+=("${token}")
done < <(
    grep -hoE "${CURRENT_VENDOR_NAMESPACE}\\\\{1,2}[A-Za-z_][A-Za-z0-9_]*" "${FILES[@]}" 2>/dev/null \
        | grep -vE "^${CURRENT_VENDOR_NAMESPACE}\\\\{1,2}${CURRENT_PACKAGE_NAMESPACE}$" \
        | sort -u
)

# Longest token first: one protected token can be a prefix of another — a
# dependency "vendor/package" next to "vendor/package-extra", or a namespace
# "VENDOR\Testing" next to "VENDOR\TestingFramework". Masking the shorter one
# first would leave the tail of the longer one exposed to the replacements.
if [ "${#PROTECTED_TOKENS[@]}" -gt 1 ]; then
    mapfile -t PROTECTED_TOKENS < <(
        printf '%s\n' "${PROTECTED_TOKENS[@]}" \
            | "${AWK}" '{ print length "\t" $0 }' \
            | sort -rn -k1,1 \
            | cut -f2-
    )
fi

# ---------------------------------------------------------------------------
# Apply the replacements. The replacement is literal (not a regular expression)
# and done with awk, so backslashes in namespaces need no escaping dance.
# ---------------------------------------------------------------------------
replace_in_file() {
    local file="$1" tmp
    tmp="$(mktemp)"
    AWK_SEARCH="$2" AWK_REPLACE="$3" "${AWK}" '
        BEGIN {
            search = ENVIRON["AWK_SEARCH"]
            replace = ENVIRON["AWK_REPLACE"]
            searchLength = length(search)
        }
        {
            line = $0
            out = ""
            while ((position = index(line, search)) > 0) {
                out = out substr(line, 1, position - 1) replace
                line = substr(line, position + searchLength)
            }
            print out line
        }
    ' "${file}" > "${tmp}"
    cat "${tmp}" > "${file}"
    rm -f "${tmp}"
}

info "Rewriting identifiers"
CHANGED_FILES=0
for file in "${FILES[@]}"; do
    declare -a APPLIED=()
    declare -a MASKED=()

    # Work on a copy, so a dry run reports exactly what a real run would do:
    # the protected tokens are masked in the copy, and a replacement matching
    # nothing but a masked token is neither reported nor applied.
    WORK_FILE="$(mktemp)"
    cat "${file}" > "${WORK_FILE}"

    for index in "${!PROTECTED_TOKENS[@]}"; do
        if ! grep -qF -- "${PROTECTED_TOKENS[${index}]}" "${WORK_FILE}" 2>/dev/null; then
            continue
        fi
        MASKED+=("${index}")
        replace_in_file "${WORK_FILE}" "${PROTECTED_TOKENS[${index}]}" "@@PROTECTED-${index}@@"
    done

    # Each search is replaced by a placeholder rather than by its final value,
    # and the placeholders are resolved once every search has been processed.
    #
    # Writing the final value immediately would expose it to the searches that
    # follow, and a new identifier legitimately contains the old one whenever
    # the new repository name does: renaming "some-name" to "my-some-name"
    # first rewrites "<owner>/some-name" to "<owner>/my-some-name", and the
    # bare repository search would then find "some-name" inside what was just
    # written and turn it into "my-my-some-name". A placeholder contains no
    # identifier, so nothing rewritten in this pass can be rewritten again.
    for index in "${!REPLACEMENT_SEARCH[@]}"; do
        search="${REPLACEMENT_SEARCH[${index}]}"
        if ! grep -qF -- "${search}" "${WORK_FILE}" 2>/dev/null; then
            continue
        fi
        APPLIED+=("${index}")
        replace_in_file "${WORK_FILE}" "${search}" "@@REPLACEMENT-${index}@@"
    done

    for index in "${APPLIED[@]}"; do
        replace_in_file "${WORK_FILE}" "@@REPLACEMENT-${index}@@" "${REPLACEMENT_REPLACE[${index}]}"
    done

    if [ "${#MASKED[@]}" -gt 0 ]; then
        for index in "${MASKED[@]}"; do
            replace_in_file "${WORK_FILE}" "@@PROTECTED-${index}@@" "${PROTECTED_TOKENS[${index}]}"
        done
    fi

    if [ "${#APPLIED[@]}" -gt 0 ]; then
        CHANGED_FILES=$((CHANGED_FILES + 1))
        REPORT=""
        for index in "${APPLIED[@]}"; do
            REPORT="${REPORT}${REPORT:+ | }${REPLACEMENT_SEARCH[${index}]} -> ${REPLACEMENT_REPLACE[${index}]}"
        done
        step "${file}" "${REPORT}"
        if [ "${DRY_RUN}" -eq 0 ]; then
            cat "${WORK_FILE}" > "${file}"
        fi
    fi

    rm -f "${WORK_FILE}"
    unset APPLIED MASKED
done
step "info" "${CHANGED_FILES} of ${#FILES[@]} files rewritten"
if [ "${SKIPPED_WORKFLOW_FILES}" -gt 0 ]; then
    step "info" "${SKIPPED_WORKFLOW_FILES} GitHub Actions workflow files skipped"
fi

# GitHub Actions workflow files are not rewritten, so they must not carry any of
# the identifiers. Report it instead of leaving a stale value behind unnoticed.
declare -a STALE_WORKFLOW_FILES=()
while IFS= read -r file; do
    for index in "${!REPLACEMENT_SEARCH[@]}"; do
        if grep -qF -- "${REPLACEMENT_SEARCH[${index}]}" "${file}" 2>/dev/null; then
            STALE_WORKFLOW_FILES+=("${file}")
            break
        fi
    done
done < <(find .github/workflows -type f 2>/dev/null | sort)

if [ "${#STALE_WORKFLOW_FILES[@]}" -gt 0 ]; then
    warn "These GitHub Actions workflow files still contain template identifiers:"
    printf '         %s\n' "${STALE_WORKFLOW_FILES[@]}" >&2
    warn "They are intentionally not rewritten, because the GITHUB_TOKEN of an Actions"
    warn "run may not update files below .github/workflows/. Adjust them by hand, or"
    warn "derive the value at runtime from composer.json."
fi

# ---------------------------------------------------------------------------
# reStructuredText section adornments are as long as the title they belong to,
# so every heading with a renamed title has to be resized. Transitions
# (adornment lines that are not preceded by a title line) are left alone.
# ---------------------------------------------------------------------------
declare -a RST_FILES=()
while IFS= read -r file; do
    RST_FILES+=("${file}")
done < <(printf '%s\n' "${FILES[@]}" | grep -E '\.rst(\.txt)?$' || true)

if [ "${#RST_FILES[@]}" -gt 0 ]; then
    info "Normalizing reStructuredText section adornments"
    ADORNMENT_FILES=0
    for file in "${RST_FILES[@]}"; do
        tmp="$(mktemp)"
        "${AWK}" '
            function isAdornment(line,   character, position) {
                if (length(line) < 2) { return 0 }
                character = substr(line, 1, 1)
                if (character !~ /^[=~^*+#_-]$/) { return 0 }
                for (position = 2; position <= length(line); position++) {
                    if (substr(line, position, 1) != character) { return 0 }
                }
                return 1
            }
            function adornmentFor(line, title,   character, result) {
                character = substr(line, 1, 1)
                result = ""
                while (length(result) < length(title)) { result = result character }
                return result
            }
            { lines[NR] = $0 }
            END {
                for (i = 1; i <= NR; i++) {
                    if (!isAdornment(lines[i])) { continue }
                    if (i < 2 || lines[i - 1] == "" || isAdornment(lines[i - 1])) { continue }
                    # Underline of the title on the previous line.
                    lines[i] = adornmentFor(lines[i], lines[i - 1])
                    # Matching overline, when present.
                    if (i > 2 && isAdornment(lines[i - 2]) \
                        && substr(lines[i - 2], 1, 1) == substr(lines[i], 1, 1)) {
                        lines[i - 2] = adornmentFor(lines[i - 2], lines[i - 1])
                    }
                }
                for (i = 1; i <= NR; i++) { print lines[i] }
            }
        ' "${file}" > "${tmp}"
        if cmp -s "${file}" "${tmp}"; then
            rm -f "${tmp}"
            continue
        fi
        ADORNMENT_FILES=$((ADORNMENT_FILES + 1))
        step "${file}" "section adornments resized"
        if [ "${DRY_RUN}" -eq 0 ]; then
            cat "${tmp}" > "${file}"
        fi
        rm -f "${tmp}"
    done
    step "info" "${ADORNMENT_FILES} of ${#RST_FILES[@]} files adjusted"
fi

# ---------------------------------------------------------------------------
# Markdown tables are padded so the pipes line up, and an identifier inside a
# cell changes the width of its column when it is renamed — a longer repository
# name is enough. The "checkMarkdownTables" gate then fails in the very first
# pipeline run of the new repository, on a file nobody touched, so the tables
# are reformatted here with the algorithm that gate itself uses.
#
# Deliberately not routed through "runTests.sh -s checkMarkdownTables -- --fix":
# this runs in a fresh repository where no dependency set is installed and there
# may be no container runtime at all. "MarkdownTableFormatter.php" carries no
# dependencies for exactly that reason.
#
# Symlinks are skipped: they point at a file which is in this list itself, and
# writing through one would rewrite the target twice.
# ---------------------------------------------------------------------------
declare -a MARKDOWN_FILES=()
while IFS= read -r file; do
    [ -L "${file}" ] && continue
    MARKDOWN_FILES+=("${file}")
done < <(printf '%s\n' "${FILES[@]}" | grep -E '\.md$' || true)

if [ "${#MARKDOWN_FILES[@]}" -gt 0 ]; then
    info "Normalizing markdown tables"
    declare -a REFORMATTED_FILES=()
    while IFS= read -r file; do
        [ -z "${file}" ] && continue
        REFORMATTED_FILES+=("${file}")
    done < <("${PHP}" -r '
        require $argv[1];
        $write = $argv[2] === "0";
        $formatter = new MarkdownTableFormatter();
        foreach (array_slice($argv, 3) as $file) {
            [$formatted, $changed] = $formatter->format((string)file_get_contents($file));
            if (!$changed) {
                continue;
            }
            if ($write) {
                file_put_contents($file, $formatted);
            }
            echo $file, PHP_EOL;
        }
    ' -- "${MARKDOWN_TABLE_FORMATTER}" "${DRY_RUN}" "${MARKDOWN_FILES[@]}")

    for file in "${REFORMATTED_FILES[@]}"; do
        step "${file}" "tables reformatted"
    done
    step "info" "${#REFORMATTED_FILES[@]} of ${#MARKDOWN_FILES[@]} files adjusted"
fi

# ---------------------------------------------------------------------------
# Point the repository URLs in composer.json at the new repository. The generic
# replacement above already covers every URL built from the old package name;
# setting them explicitly additionally covers URLs that were pointing somewhere
# else entirely. Only keys that already exist are touched.
# ---------------------------------------------------------------------------
REPOSITORY_URL="https://github.com/${NEW_PACKAGE}"

info "Repository URLs in composer.json"
step "composer.json" "homepage = ${REPOSITORY_URL}"
step "composer.json" "support.issues = ${REPOSITORY_URL}/issues"
step "composer.json" "support.source = ${REPOSITORY_URL}"

if [ "${DRY_RUN}" -eq 0 ]; then
    composer_json_write_urls "${REPOSITORY_URL}"
fi

# ---------------------------------------------------------------------------
# Apply the coding guidelines. Renaming the PHP namespace changes the
# alphabetical order of the "use" statements, so the result would otherwise
# fail the "cgl" quality gate. Everything runs through the regular test runner,
# which needs a container runtime; without one the step is skipped with a hint.
# ---------------------------------------------------------------------------
apply_coding_guidelines() {
    local runTests="Build/Scripts/runTests.sh"
    # An array rather than a string, so that nothing at all is passed when
    # --container-bin was not given and the test runner keeps its own default.
    # See the initialize workflow for why it is given there.
    local containerBin=()
    if [ -n "${CONTAINER_BIN}" ]; then
        containerBin=(-b "${CONTAINER_BIN}")
    fi

    if [ "${SKIP_CGL}" -eq 1 ]; then
        step "info" "skipped (--skip-cgl) — run \"${runTests} -s cgl\" yourself"
        return 0
    fi
    if [ ! -x "${runTests}" ]; then
        warn "${runTests} not found or not executable — skipping the coding guidelines."
        return 0
    fi
    if ! command -v podman >/dev/null 2>&1 && ! command -v docker >/dev/null 2>&1; then
        warn "No container runtime (podman or docker) found — skipping the coding guidelines."
        warn "Run \"${runTests} -s cgl\" once a container runtime is available, otherwise"
        warn "the \"cgl\" quality gate will fail on the renamed \"use\" statements."
        return 0
    fi

    # Only install dependencies when they are missing, so an already prepared
    # working copy keeps the core version it was set up for.
    if [ ! -x .Build/bin/php-cs-fixer ]; then
        step "info" "installing dependencies (composerUpdate)"
        if ! "${runTests}" "${containerBin[@]}" -s composerUpdate >/dev/null 2>&1; then
            warn "\"${runTests} -s composerUpdate\" failed — skipping the coding guidelines."
            warn "Run \"${runTests} -s composerUpdate\" and \"${runTests} -s cgl\" manually."
            return 0
        fi
    fi

    step "info" "running \"${runTests} -s cgl\""
    if ! "${runTests}" "${containerBin[@]}" -s cgl >/dev/null 2>&1; then
        warn "\"${runTests} -s cgl\" failed — run it manually and check the output."
        return 0
    fi
    step "info" "coding guidelines applied"
}

info "Applying coding guidelines"
if [ "${DRY_RUN}" -eq 1 ]; then
    step "info" "skipped (dry-run)"
else
    apply_coding_guidelines
fi

# ---------------------------------------------------------------------------
# Verify the result.
# ---------------------------------------------------------------------------
if [ "${DRY_RUN}" -eq 0 ]; then
    info "Verifying composer.json"
    RESULT_PACKAGE="$(composer_json_read name)"
    RESULT_EXTENSION_KEY="$(composer_json_read extension-key)"
    RESULT_NAMESPACE="$(composer_json_read namespace)"
    RESULT_TEST_NAMESPACE="$(composer_json_read namespace-dev)"

    EXPECTED_NAMESPACE="${NEW_VENDOR_NAMESPACE}\\${NEW_PACKAGE_NAMESPACE}\\"
    EXPECTED_TEST_NAMESPACE="${NEW_VENDOR_NAMESPACE}\\${NEW_PACKAGE_NAMESPACE}\\Tests\\"

    if [ "${RESULT_PACKAGE}" != "${NEW_PACKAGE}" ]; then
        die "composer.json name is '${RESULT_PACKAGE}', expected '${NEW_PACKAGE}'."
    fi
    if [ "${RESULT_EXTENSION_KEY}" != "${NEW_EXTENSION_KEY}" ]; then
        die "composer.json extension key is '${RESULT_EXTENSION_KEY}', expected '${NEW_EXTENSION_KEY}'."
    fi
    if [ "${RESULT_NAMESPACE}" != "${EXPECTED_NAMESPACE}" ]; then
        die "composer.json root namespace is '${RESULT_NAMESPACE}', expected '${EXPECTED_NAMESPACE}'."
    fi
    if [ "${RESULT_TEST_NAMESPACE}" != "${EXPECTED_TEST_NAMESPACE}" ]; then
        die "composer.json test namespace is '${RESULT_TEST_NAMESPACE}', expected '${EXPECTED_TEST_NAMESPACE}'."
    fi

    step "composer.json" "name           = ${RESULT_PACKAGE}"
    step "composer.json" "extension key  = ${RESULT_EXTENSION_KEY}"
    step "composer.json" "root namespace = ${RESULT_NAMESPACE}"
    step "composer.json" "test namespace = ${RESULT_TEST_NAMESPACE}"
fi

info "Finished initialization of ${NEW_PACKAGE}"
if [ "${DRY_RUN}" -eq 0 ]; then
    printf '   %s\n' "Review the changes and commit them, for example:"
    printf '   %s\n' "git add -A && git commit -m '[TASK] Adjust repository'"
fi
