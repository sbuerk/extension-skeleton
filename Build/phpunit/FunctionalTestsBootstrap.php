/**
 * Bootstrap of the functional test suite, defined in FunctionalTests.xml and
 * called by phpunit before instantiating the test suites.
 *
 * Derived from the boilerplate shipped with typo3/testing-framework in
 * "Resources/Core/Build/FunctionalTestsBootstrap.php", baselined from version
 * 9.6.1. Re-check it against that file when the testing-framework is updated.
 *
 * Deliberate deviations from the boilerplate:
 *
 * * Fully qualified class names are replaced by imports and the closure is
 *   typed, both to satisfy the coding guidelines of this repository.
 * * The fixture extensions collected by the "sbuerk/fixture-packages" composer
 *   plugin are adopted, see below.
 *
 * The recommended way to execute the suite is "Build/Scripts/runTests.sh".
 */
(static function (): void {
    // Hand the fixture extensions below "Tests/Functional/Fixtures/Extensions/"
    // to the ComposerPackageManager of the testing-framework, so a functional
    // test can name them in $testExtensionsToLoad by composer package name or
    // extension key instead of by path. The class is generated by the composer
    // plugin "sbuerk/fixture-packages", which is a development dependency only —
    // hence the guard.
    if (class_exists(AvailableFixturePackages::class)) {
        (new AvailableFixturePackages())->adoptFixtureExtensions();
    }

    $testbase = new Testbase();
    $testbase->defineOriginalRootPath();
    $testbase->createDirectory(ORIGINAL_ROOT . 'typo3temp/var/tests');
    $testbase->createDirectory(ORIGINAL_ROOT . 'typo3temp/var/transient');
})();
